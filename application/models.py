class ExpandedURLValidator(URLValidator):
    schemes = ["file", "ftp", "ftps", "http", "https", "s3", "ssh", "urn", "ws", "wss"]

    def __call__(self, value):
        if not isinstance(value, str) or len(value) > self.max_length:
            raise ValidationError(self.message, code=self.code, params={"value": value})
        if self.unsafe_chars.intersection(value):
            raise ValidationError(self.message, code=self.code, params={"value": value})
        # Check if the scheme is valid.
        scheme = value.split("://")[0].lower()
        if scheme not in self.schemes:
            raise ValidationError(self.message, code=self.code, params={"value": value})

        # Then check full URL
        try:
            urlsplit(value)
        except ValueError as e:
            raise ValidationError(
                self.message, code=self.code, params={"value": value}
            ) from e

    @property
    def message(self):
        return f"Enter a valid URL. Valid schemes: {', '.join(self.schemes)}"


class CPEDictionary(models.Model):
    """
    Represents a CPE Dictionary.

    Corresponds conceptually to: <cpe_dict:cpe-list>
    NIST IR 7697, Section 5.1.
    """

    # Optional bookkeeping useful for imported dictionaries.
    source_uri = models.CharField(blank=True, validators=[ExpandedURLValidator()])
    imported_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "CPE Dictionary <cpe_dict:cpe-list>"
        verbose_name_plural = "CPE Dictionaries [<cpe_dict:cpe-list>]"

    def __str__(self):
        return f"Dictionary {self.id} {self.source_uri}"


class CPEGenerator(models.Model):
    """
    Corresponds to: <cpe_dict:generator>

    NIST IR 7697 Section 5.2 defines:
      - product_name
      - product_version
      - schema_version
      - timestamp
    """

    dictionary = models.OneToOneField(
        CPEDictionary,
        on_delete=models.CASCADE,
        related_name="generator",
    )

    product_name = models.CharField(
        max_length=255,
        null=True,
    )

    product_version = models.CharField(
        max_length=255,
        null=True,
    )

    schema_version = models.CharField(
        max_length=255,
        default="2.3",
    )

    timestamp = models.DateTimeField(auto_created=True)

    class Meta:
        verbose_name = "CPE Generator <cpe_dict:generator>"
        verbose_name_plural = "CPE Generators [<cpe_dict:generator>]"

    def __str__(self):
        if self.product_name:
            return f"{self.product_name} {self.product_version}".strip()

        return f"Generated by {self.product_name} version {self.product_version} for cpe schema {self.schema_version}"


class CPEItem(models.Model):
    """
    The primary CPE dictionary entry.

    Corresponds to: <cpe_dict:cpe-item>

    NIST IR 7697 Section 5.3.

    The dictionary maintains both the legacy CPE 2.2 URI binding and
    the CPE 2.3 formatted-string binding.
    """

    dictionary = models.ForeignKey(
        CPEDictionary, on_delete=models.CASCADE, related_name="items"
    )

    # CPE 2.2 URI binding.
    name = models.CharField(max_length=2048, help_text="CPE 2.2 URI binding.")

    deprecated = models.BooleanField(
        default=False, help_text="Whether or not the name has been deprecated."
    )

    # Legacy 2.2 deprecation information.
    deprecated_by_cpe22 = models.CharField(
        max_length=2048,
        null=True,
        help_text="Legacy CPE 2.2 name that deprecated this entry.",
    )

    deprecation_date = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    cpe_name_id = models.UUIDField(
        blank=True,
        help_text="Unique CPE identifier. A new field added by NVD.",
        primary_key=True,
    )

    class Meta:
        verbose_name = "CPE Item <cpe_dict:cpe-item>"
        verbose_name_plural = "CPE Items [<cpe_dict:cpe-item>]"
        indexes = [
            models.Index(fields=["name"]),
            models.Index(fields=["deprecated"]),
        ]
        ordering = ["-created_at"]

    def __str__(self):
        return self.cpe23.name


