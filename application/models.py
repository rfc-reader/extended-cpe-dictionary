class CPEWellFormedName(models.Model):
    """
    A well-formed CPE name (WFN) that identifies a single product class

    A WFN has eleven attributes:

        part
        vendor
        product
        version
        update
        edition
        language
        sw_edition
        target_sw
        target_hw
        other

    This model stores the parsed representation in addition to the
    canonical CPE 2.3 formatted string stored by CPE23Item.
    """

    PART_APPLICATION = "a"
    PART_OPERATING_SYSTEM = "o"
    PART_HARDWARE = "h"

    PART_CHOICES = (
        (PART_APPLICATION, "Application"),
        (PART_OPERATING_SYSTEM, "Operating System"),
        (PART_HARDWARE, "Hardware"),
    )

    cpe23_item = models.OneToOneField(
        CPE23Item,
        on_delete=models.CASCADE,
        related_name="wfn",
    )

    part = models.CharField(max_length=1, choices=PART_CHOICES)
    vendor = models.CharField(max_length=255)
    product = models.CharField(max_length=255)
    version = models.CharField(max_length=255)
    update = models.CharField(max_length=255, blank=True)
    edition = models.CharField(max_length=255, blank=True)
    language = models.CharField(max_length=255, blank=True)
    sw_edition = models.CharField(max_length=255, blank=True)
    target_sw = models.CharField(max_length=255, blank=True)
    target_hw = models.CharField(max_length=255, blank=True)
    other = models.CharField(max_length=255, blank=True)

    class Meta:
        verbose_name = "CPE WFN"
        verbose_name_plural = "CPE WFNs"

        indexes = [
            models.Index(fields=["part"]),
            models.Index(fields=["vendor"]),
            models.Index(fields=["product"]),
            models.Index(fields=["version"]),
            models.Index(fields=["vendor", "product"]),
            models.Index(
                fields=[
                    "part",
                    "vendor",
                    "product",
                    "version",
                ]
            ),
        ]

    def __str__(self):
        return ":".join(
            [
                self.part,
                self.vendor,
                self.product,
                self.version,
                self.update,
                self.edition,
                self.language,
                self.sw_edition,
                self.target_sw,
                self.target_hw,
                self.other,
            ]
        )

    def clean(self):
        """
        Basic CPE Dictionary 2.3 acceptance rules.

        NIST IR 7697 Section 6.1 requires known data for:
            part
            vendor
            product
            version

        ANY is not permitted for these four fields.
        """

        required = {
            "part": self.part,
            "vendor": self.vendor,
            "product": self.product,
            "version": self.version,
        }

        for field, value in required.items():
            if not value:
                raise ValidationError(
                    {field: "This CPE attribute must contain known data."}
                )

            if value == ANY:
                raise ValidationError(
                    {field: "ANY is not permitted for identifier names."}
                )

        if ANY in self.vendor or "?" in self.vendor:
            raise ValidationError({"vendor": "Wildcard characters are not allowed."})

        if ANY in self.product or "?" in self.product:
            raise ValidationError({"product": "Wildcard characters are not allowed."})

    @classmethod
    def create_from_cpe23_model(cls, cpe23_item: CPE23Item):
        (
            part,
            vendor,
            product,
            version,
            update,
            edition,
            language,
            sw_edition,
            target_sw,
            target_hw,
            other,
        ) = cpe23_formatted_string_to_wfn(cpe23_item.name)
        cls.objects.create(
            cpe23_item=cpe23_item,
            part=part,
            vendor=vendor,
            product=product,
            version=version,
            update=update,
            edition=edition,
            language=language,
            sw_edition=sw_edition,
            target_sw=target_sw,
            target_hw=target_hw,
            other=other,
        )


class CPETitle(models.Model):
    """
    Corresponds to: <cpe_dict:title>

    A CPE item may have one title per language.
    """

    item = models.ForeignKey(
        CPEItem,
        on_delete=models.CASCADE,
        related_name="titles",
        help_text="The UUID of the CPE item",
    )

    language = models.CharField(max_length=16, default="en-US", help_text="xml:lang")
    value = models.CharField(max_length=2048, help_text="The title text")

    class Meta:
        verbose_name = "CPE Title <cpe_dict:title>"
        verbose_name_plural = "CPE Titles [<cpe_dict:title>]"

        constraints = [
            models.UniqueConstraint(
                fields=["item", "language"],
                name="unique_cpe_title_language",
            ),
        ]

        indexes = [
            models.Index(fields=["language"]),
        ]

    def __str__(self):
        return self.value


