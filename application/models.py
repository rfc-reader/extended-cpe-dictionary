class CPEDeprecatedBy(models.Model):
    """
    A CPE that caused another CPE to be deprecated.

    One deprecation can contain one or more deprecated-by entries.

    Corresponds to: <cpe_dict_ext:deprecation-by>

    IMPORTANT:
    `name` is intentionally a string rather than a ForeignKey.

    NIST explicitly allows this value to contain a wildcard and
    therefore represent a set of products rather than an identifier
    CPE name.
    """

    NAME_CORRECTION = "NAME_CORRECTION"
    NAME_REMOVAL = "NAME_REMOVAL"
    ADDITIONAL_INFORMATION = "ADDITIONAL_INFORMATION"
    UNKNOWN = "UNKNOWN"

    DEPRECATION_TYPE_CHOICES = (
        (NAME_CORRECTION, "Name Correction"),
        (NAME_REMOVAL, "Name Removal"),
        (
            ADDITIONAL_INFORMATION,
            "Additional Information Discovery",
        ),
        (
            UNKNOWN,
            "Reason Unknown",
        ),  # DEPRECATION_TYPE missing from Official CPE Dictionary exports
    )

    deprecation = models.ForeignKey(
        CPEDeprecation,
        on_delete=models.CASCADE,
        related_name="deprecated_by",
    )

    deprecation_type = models.CharField(
        max_length=32,
        choices=DEPRECATION_TYPE_CHOICES,
    )

    name = models.CharField(
        max_length=4096,
        blank=True,
        help_text=(
            "CPE 2.3 name that deprecates this one. May contain wildcards because "
            "it could have been expanded into a product set."
        ),
    )

    class Meta:
        verbose_name = "CPE Deprecation By <cpe_dict_ext:deprecation-by>"
        verbose_name_plural = "CPE Deprecation Bys [<cpe_dict_ext:deprecation-by>]"

    def __str__(self):
        return self.name or self.deprecation_type
